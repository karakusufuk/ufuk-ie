// Reports every text element below the WCAG AA contrast ratio (axe-core color-contrast) on all 14 pages. Reports only, changes nothing.
import fs from 'node:fs';
import { chromium } from 'playwright';
const base = (process.argv[2] || 'http://localhost:8101').replace(/\/?$/, '/');
const axe = fs.readFileSync(new URL('./node_modules/axe-core/axe.min.js', import.meta.url), 'utf8');
const pages = ['index', 'work', 'about', 'contact', 'brennock', 'reilly', 'bawn', 'fennel', 'kenilworth', 'garvey', 'tierney', 'midland', 'monument', 'lear', 'ashgrove'];
const b = await chromium.launch({ channel: 'chrome' });
const out = ['# Contrast report (axe-core, rules: color-contrast, AA 4.5:1 / 3:1 large)', '', 'Generated by `tools/contrast.mjs`. Nothing here was changed.', ''];
for (const p of pages) {
  const page = await b.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
  await page.goto(base + p + '.html'); await page.waitForTimeout(2500);
  await page.addScriptTag({ content: axe });
  const res = await page.evaluate(async () => (await axe.run(document, { runOnly: ['color-contrast'] })).violations.flatMap((v) => v.nodes.map((n) => ({ sel: n.target.join(' '), html: n.html.slice(0, 90), msg: (n.any[0] && n.any[0].message) || '' }))));
  const groups = new Map();
  for (const r of res) { const m = r.msg.match(/contrast of ([\d.]+) \(foreground color: (#\w+), background color: (#\w+), font size: ([\d.]+pt \(\d+px\))/) || []; const key = `${m[2]} on ${m[3]} (${m[1]}:1), ${m[4]}`; if (!groups.has(key)) groups.set(key, []); groups.get(key).push(r.html); }
  out.push(`## ${p}.html — ${res.length} element(s)`);
  for (const [k, v] of groups) out.push(`- ${k}: ${v.length} × e.g. \`${v[0].replace(/\n/g, ' ')}\``);
  if (!res.length) out.push('- none');
  out.push('');
  console.log(p, res.length);
  await page.close();
}
await b.close();
fs.writeFileSync(new URL('../docs/contrast-report.md', import.meta.url), out.join('\n'));
